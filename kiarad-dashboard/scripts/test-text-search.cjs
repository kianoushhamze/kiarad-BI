// Real helper, synthetic records, no browser/storage/database/network.
const ts = require('typescript');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const source = fs.readFileSync(path.join(__dirname, '../lib/text-search.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const target = { exports: {} };
new Function('exports', 'module', compiled)(target.exports, target);
const { matchesSearch, normalizeSearchText, uniqueSearchOptions } = target.exports;
let checks = 0;
function equal(actual, expected) { assert.deepEqual(actual, expected); checks++; }
equal(normalizeSearchText('  كرم آبرسان ياس ۱۲۳  '), 'کرم ابرسان یاس 123');
equal(matchesSearch('ابر كرم', 'کرم آبرسان یاس'), true);
equal(matchesSearch('شام MIL', 'MILITO شامپو روزانه'), true);
equal(matchesSearch('ضدآفتاب', 'کرم ضد آفتاب'), true);
equal(matchesSearch('ضد افتاب', 'ضدآفتاب رنگی'), true);
equal(matchesSearch('۱۲۳', 'کد 12345'), true);
equal(matchesSearch('١٢٣', 'کد ۱۲۳۴۵'), true);
equal(matchesSearch('رازي كرمان', 'داروخانه رازی', 'کرمان'), true);
equal(matchesSearch('كرمان را', 'داروخانه رازی', 'کرمان'), true);
equal(matchesSearch('آبرسان ناموجود', 'کرم آبرسان یاس'), false);
equal(matchesSearch('کرمان', 'داروخانه رازی', 'تهران'), false);
equal(matchesSearch('', null, undefined), true);
equal(matchesSearch('  ', 'هر کالا'), true);
equal(matchesSearch('%_', 'هر کالا'), true);
equal(uniqueSearchOptions(['کالای قدیمی آزاد', 'كالاى قديمى آزاد', 'کالای واقعی', null, '']), ['کالای قدیمی آزاد', 'کالای واقعی']);
const options = uniqueSearchOptions(Array.from({ length: 273 }, (_, index) => `کالای واقعی ${index + 1}`));
equal(options.length, 273);
equal(options.filter(name => matchesSearch('273 واقعی', name)), ['کالای واقعی 273']);
const freeText = 'محصول خارج از کاتالوگ / توضیح دلخواه';
equal(uniqueSearchOptions([...options, freeText]).includes(freeText), true);
equal(freeText, 'محصول خارج از کاتالوگ / توضیح دلخواه');
const crmSource = fs.readFileSync(path.join(__dirname, '../app/crm/page.tsx'), 'utf8');
equal(crmSource.includes('const PRODUCTS ='), false);
equal(crmSource.includes('useState("سوآلین ویرا")'), false);
equal(crmSource.includes('product_discussed: product'), true);
equal(crmSource.includes('"/catalog/products"'), true);
equal(crmSource.includes('id="crm-discussed-product" list="crm-product-options"'), true);
console.log(JSON.stringify({ checks, passed: true, network: false, synthetic_only: true }));
